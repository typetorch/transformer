//go:build ignore

// Generates constants_generated.go: re-declares typescript-go's exported constants with the given prefixes, since a
// type alias carries methods across the internal/ boundary but not constants.
//
//	go run gen/main.go <typescript-go checkout>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var packages = []struct {
	dir, name string
	prefixes  []string
}{
	{"internal/ast", "ast", []string{"Kind", "SymbolFlags", "NodeFlags", "ModifierFlags", "TokenFlags", "CheckFlags"}},
	{"internal/checker", "checker", []string{"TypeFlags", "ObjectFlags", "SignatureKind", "ElementFlags", "TypeFormatFlags"}},
	{"internal/printer", "printer", []string{"GeneratedIdentifierFlags", "EmitFlags"}},
	{"internal/diagnostics", "diagnostics", []string{"Category"}},
}

func main() {
	root := os.Args[1]
	var out bytes.Buffer
	out.WriteString("// Code generated by gen/main.go; DO NOT EDIT.\n\npackage goblox\n\nimport (\n")
	for _, p := range packages {
		fmt.Fprintf(&out, "\t%q\n", "github.com/microsoft/typescript-go/"+p.dir)
	}
	out.WriteString(")\n\nconst (\n")
	for _, p := range packages {
		names := collect(filepath.Join(root, p.dir), p.prefixes)
		for _, name := range names {
			fmt.Fprintf(&out, "\t%s = %s.%s\n", name, p.name, name)
		}
	}
	out.WriteString(")\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("constants_generated.go", src, 0o644); err != nil {
		panic(err)
	}
}

func collect(dir string, prefixes []string) []string {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	if err != nil {
		panic(err)
	}
	seen := map[string]bool{}
	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				gen, ok := decl.(*ast.GenDecl)
				if !ok || gen.Tok != token.CONST {
					continue
				}
				for _, spec := range gen.Specs {
					for _, name := range spec.(*ast.ValueSpec).Names {
						if !name.IsExported() {
							continue
						}
						for _, prefix := range prefixes {
							if strings.HasPrefix(name.Name, prefix) {
								seen[name.Name] = true
							}
						}
					}
				}
			}
		}
	}
	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
